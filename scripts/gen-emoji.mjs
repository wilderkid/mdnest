// Generate src/editor/emoji-data.ts from gemoji (MIT, https://github.com/wooorm/gemoji).
// Compact form: one string of shortcode\u0001char pairs, split at runtime.
// Usage: node scripts/gen-emoji.mjs
import { gemoji } from "gemoji";
import fs from "node:fs";

// Flags are long regional-indicator sequences and rarely typed as shortcodes.
// One name per emoji keeps the module under 40 KB.
const rows = [];
const seen = new Set();
for (const g of gemoji) {
  if (!g.emoji || !g.names?.length) continue;
  if (g.category === "Flags") continue;
  const name = g.names[0];
  if (!/^[a-z0-9_+-]+$/i.test(name) || seen.has(name)) continue;
  seen.add(name);
  rows.push(name + "\u0001" + g.emoji);
}
rows.sort((a, b) => a.localeCompare(b));
const entries = rows.map((row) => {
  const i = row.indexOf("\u0001");
  return [row.slice(0, i), row.slice(i + 1)];
});
const body = entries.map(([name, emoji]) => `${JSON.stringify(name)}:${JSON.stringify(emoji)}`).join(",");
const out = `// Generated by scripts/gen-emoji.mjs from the gemoji package (MIT).
// Source: https://github.com/wooorm/gemoji — emoji names from github/gemoji (MIT).
// Do not edit by hand. ${entries.length} shortcodes.

export const EMOJI: Record<string, string> = {${body}};
`;
const dest = new URL("../src/editor/emoji-data.ts", import.meta.url);
fs.writeFileSync(dest, out);
const bytes = Buffer.byteLength(out);
console.log(`wrote ${rows.length} shortcodes, ${bytes} bytes raw`);
if (bytes > 40 * 1024) {
  console.error("emoji-data.ts is over 40 KB");
  process.exit(1);
}
